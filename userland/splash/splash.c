static const u8 *glyph(char c)
{
    u8 u = (u8)c;
    if (u < FONT_FIRST || u > FONT_LAST)
        u = '?';
    return FONT[u - FONT_FIRST];
}

/* ── The framebuffer ──────────────────────────────────────────────────
 * Two ioctls describe it. Rather than declare the kernel's structures -
 * they are large, and most of what is in them is for setting a mode, not
 * reading one - we read the fields we need out of a byte buffer at the
 * offsets the kernel puts them at. Those offsets are part of the ABI and
 * cannot move.
 */
#define FBIOGET_VSCREENINFO  0x4600
#define FBIOGET_FSCREENINFO  0x4602

#define VAR_SIZE        160
#define VAR_XRES          0
#define VAR_YRES          4
#define VAR_BPP          24
#define VAR_RED_OFF      32     /* struct fb_bitfield: offset, length, msb */
#define VAR_GREEN_OFF    44
#define VAR_BLUE_OFF     56

#define FIX_SIZE         80
#define FIX_LINE_LENGTH  48

typedef struct {
    u32 xres, yres, bpp, line_length;
    u32 r_off, r_len, g_off, g_len, b_off, b_len;
} fb_t;

static bool fb_query(int fd, fb_t *fb)
{
    u8 var[VAR_SIZE], fix[FIX_SIZE];
    memset(var, 0, sizeof(var));
    memset(fix, 0, sizeof(fix));

    if (lp_ioctl(fd, FBIOGET_VSCREENINFO, var) < 0) return false;
    if (lp_ioctl(fd, FBIOGET_FSCREENINFO, fix) < 0) return false;

    fb->xres        = *(u32 *)(var + VAR_XRES);
    fb->yres        = *(u32 *)(var + VAR_YRES);
    fb->bpp         = *(u32 *)(var + VAR_BPP);
    fb->r_off       = *(u32 *)(var + VAR_RED_OFF);
    fb->r_len       = *(u32 *)(var + VAR_RED_OFF + 4);
    fb->g_off       = *(u32 *)(var + VAR_GREEN_OFF);
    fb->g_len       = *(u32 *)(var + VAR_GREEN_OFF + 4);
    fb->b_off       = *(u32 *)(var + VAR_BLUE_OFF);
    fb->b_len       = *(u32 *)(var + VAR_BLUE_OFF + 4);
    fb->line_length = *(u32 *)(fix + FIX_LINE_LENGTH);

    if (fb->xres == 0 || fb->yres == 0 || fb->line_length == 0)
        return false;
    if (fb->bpp != 16 && fb->bpp != 32)
        return false;               /* 8-bit palettes need a colour map */
    return true;
}

/* Pack an 8-bit-per-channel colour the way this particular framebuffer
 * wants it. The bit positions come from the driver, so this is right on
 * a 32-bit XRGB screen and on a 16-bit 565 one without either being a
 * special case. */
static u32 pack(const fb_t *fb, u8 r, u8 g, u8 b)
{
    u32 v = 0;
    v |= (u32)(r >> (8 - fb->r_len)) << fb->r_off;
    v |= (u32)(g >> (8 - fb->g_len)) << fb->g_off;
    v |= (u32)(b >> (8 - fb->b_len)) << fb->b_off;
    return v;
}

static void put_pixel(u8 *row, const fb_t *fb, u32 x, u32 v)
{
    if (x >= fb->xres)
        return;
    if (fb->bpp == 32)
        *(u32 *)(row + x * 4) = v;
    else
        *(u16 *)(row + x * 2) = (u16)v;
}

/* One line of text, at a scale, drawn into whichever row we are on. */
typedef struct {
    const char *text;
    u32         x, y;       /* top left, in pixels */
    u32         scale;
    u32         colour;
} label_t;

static void draw_label_row(u8 *row, const fb_t *fb, const label_t *l, u32 y)
{
    u32 height = FONT_H * l->scale;
    if (y < l->y || y >= l->y + height)
        return;

    u32 grow = (y - l->y) / l->scale;          /* which row of the glyph */

    for (u32 i = 0; l->text[i]; i++) {
        const u8 *g    = glyph(l->text[i]);
        u8        bits = g[grow];
        u32       x0   = l->x + i * FONT_W * l->scale;

        for (u32 bit = 0; bit < FONT_W; bit++) {
            if (!(bits & (0x80 >> bit)))
                continue;
            for (u32 s = 0; s < l->scale; s++)
                put_pixel(row, fb, x0 + bit * l->scale + s, l->colour);
        }
    }
}

static u32 text_width(const char *s, u32 scale)
{
    return (u32)strlen(s) * FONT_W * scale;
}

int main(int argc, char **argv)
{
    const char *dev = "/dev/fb0";
    if (argc > 1 && strcmp(argv[1], "-h") == 0) {
        printf("usage: splash [device]\n");
        printf("  draws the boot screen on the framebuffer (default %s)\n", dev);
        return 0;
    }
    if (argc > 1)
        dev = argv[1];

    /* Wait a little for the device to appear.
     *
     * The graphics hardware is found by probing a bus, and that finishes
     * some time after init starts - so at the moment we are run there is
     * often no /dev/fb0 yet, and being early is not a reason to give up.
     * Eight seconds covers a slow probe on a cold board without holding
     * anything up: init starts this and carries straight on, and a
     * machine with no screen simply has a process asleep for a moment. */
    long fd = -1;
    for (int waited = 0; waited <= 8000; waited += 100) {
        fd = lp_open(dev, O_WRONLY, 0);
        if (fd >= 0)
            break;
        lp_sleep_ms(100);
    }
    if (fd < 0)
        return 1;                   /* no screen attached - not an error */

    fb_t fb;
    if (!fb_query((int)fd, &fb)) {
        lp_close((int)fd);
        return 1;
    }

    /* Scale with the screen so it looks the same on a 640x480 VM window
     * and on a 1080p television. */
    u32 scale = fb.xres / 320;
    if (scale < 1) scale = 1;
    if (scale > 6) scale = 6;
    u32 small = scale > 1 ? scale - 1 : 1;

    label_t labels[3] = {
        { "test_a_123_LPzero2W_img", 0, 0, scale,
          pack(&fb, 0xE8, 0xE8, 0xF0) },
        { "Raspberry Pi Zero 2 W  /  BCM2710A1", 0, 0, small,
          pack(&fb, 0x9A, 0xA4, 0xB8) },
        { "Linux, built from scratch", 0, 0, small,
          pack(&fb, 0x9A, 0xA4, 0xB8) },
    };

    /* Centred horizontally, sitting a little above the middle - text
     * placed dead centre reads as slightly low. */
    u32 block_top = fb.yres / 2 - FONT_H * scale * 2;
    labels[0].y = block_top;
    labels[1].y = block_top + FONT_H * scale + FONT_H * small;
    labels[2].y = labels[1].y + FONT_H * small * 2;

    for (int i = 0; i < 3; i++)
        labels[i].x = (fb.xres - text_width(labels[i].text, labels[i].scale)) / 2;

    u32 bg = pack(&fb, 0x0C, 0x10, 0x1A);

    static u8 row[16384];
    u32 rowbytes = fb.line_length;
    if (rowbytes > sizeof(row)) {
        lp_close((int)fd);
        return 1;                   /* wider than we are prepared for */
    }

    for (u32 y = 0; y < fb.yres; y++) {
        /* Repaint the row background, then whatever text falls on it. */
        for (u32 x = 0; x < fb.xres; x++)
            put_pixel(row, &fb, x, bg);
        for (int i = 0; i < 3; i++)
            draw_label_row(row, &fb, &labels[i], y);

        if (lp_write((int)fd, row, rowbytes) != (long)rowbytes)
            break;                  /* short write: stop rather than tear */
    }

    lp_close((int)fd);
    return 0;
}
