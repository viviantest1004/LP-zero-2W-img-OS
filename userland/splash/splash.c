/* splash - the boot screen, drawn on the framebuffer.
 *
 * The bare-metal firmware used to draw this: it asked the GPU for a
 * framebuffer over the mailbox and wrote pixels into it. That firmware
 * and Linux cannot both be the kernel the GPU loads, so when the board
 * started booting Linux the splash went with it.
 *
 * This is the same picture, drawn the same way, one layer higher up.
 * Linux hands us the framebuffer as /dev/fb0 and tells us its shape
 * through two ioctls; everything after that is the same arithmetic the
 * firmware did. It works on the board, where the GPU set the mode up,
 * and in a virtual machine, where the emulated card did - neither one
 * needs to be treated differently.
 *
 * Written a row at a time rather than into one big buffer: a 1080p
 * screen is 8MB and this runs during boot on a board with 512MB, so
 * asking for 8MB here would be taking it from everything else at exactly
 * the wrong moment. One row is 8KB.
 */
